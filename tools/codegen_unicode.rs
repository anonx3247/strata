//! Writes `compiler/unicode` (Strata text): the Unicode tables `src/llvm.rs`
//! builds from Rust's standard library for `to_upper`, `to_lower` and
//! `is_alpha` (`case_table`, `char_ranges`), so that `compiler/codegen`
//! emits the same ones.
//!
//!     rustc -O tools/codegen_unicode.rs -o /tmp/codegen_unicode
//!     /tmp/codegen_unicode > /tmp/unicode.st
//!     strata --file compiler edit unicode < /tmp/unicode.st
//!
//! Run it with the toolchain that builds `strata`, so both have the same
//! Unicode version. Each table is a string of decimal numbers separated by
//! spaces: a case table's rows of 4 (the character, then up to 3 it maps
//! to, 0 for none), a range table's pairs (first, last).

fn case_table(upper: bool) -> Vec<u32> {
    let mut out = vec![];
    for c in (0..=0x10FFFFu32).filter_map(char::from_u32) {
        let to: Vec<char> = if upper { c.to_uppercase().collect() } else { c.to_lowercase().collect() };
        if to != [c] {
            let mut row = [c as u32, 0, 0, 0];
            for (i, x) in to.iter().enumerate() {
                row[i + 1] = *x as u32;
            }
            out.extend(row);
        }
    }
    out
}

fn char_ranges(alpha: bool) -> Vec<u32> {
    let has = |c: char| {
        if alpha {
            c.is_alphabetic()
        } else {
            c.is_lowercase() || c.is_uppercase() || c.to_lowercase().ne([c]) || c.to_uppercase().ne([c])
        }
    };
    let mut out: Vec<[u32; 2]> = vec![];
    for c in (0..=0x10FFFFu32).filter_map(char::from_u32).filter(|c| has(*c)) {
        match out.last_mut() {
            Some(r) if r[1] + 1 == c as u32 => r[1] = c as u32,
            _ => out.push([c as u32, c as u32]),
        }
    }
    out.into_iter().flatten().collect()
}

fn table(name: &str, doc: &str, xs: &[u32]) {
    let text: Vec<String> = xs.iter().map(|x| x.to_string()).collect();
    println!("/// {doc}\npub fn {name}() -> String {{\n  \"{}\"\n}}\n", text.join(" "));
}

fn main() {
    println!("// unicode — the Unicode tables compiler/codegen emits for `to_upper`,");
    println!("// `to_lower` and `is_alpha`, as src/llvm.rs builds them from Rust's");
    println!("// standard library. Generated by tools/codegen_unicode.rs: don't edit.\n");
    table("case_upper", "`to_upper`'s mappings: rows of 4 (a character, then up to 3).", &case_table(true));
    table("case_lower", "`to_lower`'s mappings: rows of 4 (a character, then up to 3).", &case_table(false));
    table("alpha_ranges", "Unicode's Alphabetic, as ranges (first, last).", &char_ranges(true));
    table("cased_ranges", "The characters with a case, as ranges (first, last).", &char_ranges(false));
}
