#!/usr/bin/env python3
"""Writes `std.unicode_tables` (Strata text) from regex-syntax's Unicode tables.

    python3 tools/unicode_tables.py ~/.cargo/registry/src/*/regex-syntax-0.8.12/src/unicode_tables \
      > /tmp/unicode_tables.st
    cd std && ../target/release/strata edit unicode_tables < /tmp/unicode_tables.st

regex-syntax's tables are made by ucd-generate from the Unicode Character
Database; taking them keeps `std.regex` and the `regex` crate (the reference
it is tested against) on the same data. Once the crates are gone, this reads
the UCD files directly.

A set of code points is written as a string of decimal numbers separated by
spaces, two per range: the gap since the previous range's end (+1), then the
range's length - 1 (`std.unicode.decode` reads it back).
"""
import os
import re
import sys
import textwrap

CHAR = r"'(\\u\{[0-9a-fA-F]+\}|\\x[0-9a-fA-F]{2}|\\.|[^'\\])'"


def char(lit):
    if lit.startswith("\\u{"):
        return int(lit[3:-1], 16)
    if lit.startswith("\\x"):
        return int(lit[2:], 16)
    if lit.startswith("\\"):
        return {"n": 10, "t": 9, "r": 13, "0": 0, "\\": 92, "'": 39, '"': 34}[lit[1]]
    assert len(lit) == 1, lit
    return ord(lit)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def tables(src):
    """Every `pub const NAME: &'static [(char, char)] = &[...];` in a file."""
    out = {}
    for m in re.finditer(r"pub const ([A-Z0-9_]+): &'static \[\(char, char\)\] =\s*&\[(.*?)\];", src, re.S):
        pairs = re.findall(r"\(" + CHAR + r",\s*" + CHAR + r"\)", m.group(2))
        out[m.group(1)] = [(char(a), char(b)) for a, b in pairs]
    return out


def by_name(src):
    m = re.search(r"pub const BY_NAME: [^=]*=\s*&\[(.*?)\];", src, re.S)
    return re.findall(r'\("([^"]+)",\s*([A-Z0-9_]+)\)', m.group(1))


def encode(ranges):
    nums = []
    prev = -1
    for a, b in ranges:
        assert a > prev, (a, prev)
        nums.append(a - prev - 1)
        nums.append(b - a)
        prev = b
    return " ".join(map(str, nums))


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def doc(out, text):
    """A `///` comment, wrapped as strata's printer wraps it."""
    for line in textwrap.wrap(text, 74, break_long_words=False, break_on_hyphens=False):
        out.append("/// " + line)


def by_name_fn(out, name, what, src):
    ts = tables(src)
    doc(out, f"{what}, by its canonical name (encoded: see `std.unicode.decode`).")
    out.append(f"pub fn {name}(name: String) -> Option[String] {{")
    out.append("  match name {")
    for n, t in by_name(src):
        out.append(f"    {lit(n)} => Some({lit(encode(ts[t]))}),")
    out.append("    _ => None,")
    out.append("  }")
    out.append("}")
    out.append("")


def main():
    d = sys.argv[1]
    f = lambda n: read(os.path.join(d, n))
    version = re.search(r"Unicode version: ([0-9]+\.[0-9]+\.[0-9]+)", f("general_category.rs")).group(1)
    out = [
        f"// std.unicode_tables — Unicode {version} character data, for `std.unicode`.",
        "//",
        "// Generated by tools/unicode_tables.py from regex-syntax's tables (made by",
        "// ucd-generate from the Unicode Character Database): don't edit, regenerate.",
        "",
        "/// The version of Unicode these tables are from.",
        "pub fn unicode_version() -> String {",
        f"  {lit(version)}",
        "}",
        "",
    ]
    by_name_fn(out, "general_category", "A general category's code points", f("general_category.rs"))
    by_name_fn(out, "script", "A script's code points", f("script.rs"))
    by_name_fn(out, "script_extension", "The code points whose script extensions include a script", f("script_extension.rs"))
    by_name_fn(out, "bool_property", "A binary property's code points", f("property_bool.rs"))
    by_name_fn(out, "grapheme_cluster_break", "A Grapheme_Cluster_Break value's code points", f("grapheme_cluster_break.rs"))
    by_name_fn(out, "word_break", "A Word_Break value's code points", f("word_break.rs"))
    by_name_fn(out, "sentence_break", "A Sentence_Break value's code points", f("sentence_break.rs"))
    by_name_fn(out, "age", "The code points assigned in exactly one version (`V1_1`, ...)", f("age.rs"))
    for name, file, const, what in [
        ("perl_word", "perl_word.rs", "PERL_WORD", "`\\\\w`: word characters"),
        ("perl_digit", "perl_decimal.rs", "DECIMAL_NUMBER", "`\\\\d`: decimal digits (Nd)"),
        ("perl_space", "perl_space.rs", "WHITE_SPACE", "`\\\\s`: White_Space"),
    ]:
        doc(out, f"{what} (encoded: see `std.unicode.decode`).")
        out.append(f"pub fn {name}() -> String {{")
        out.append(f"  {lit(encode(tables(f(file))[const]))}")
        out.append("}")
        out.append("")
    # simple case folding: each character with every other in its class
    src = f("case_folding_simple.rs")
    entries = re.findall(r"\(" + CHAR + r",\s*&\[([^\]]*)\]\)", src)
    parts = []
    prev = 0
    for c, others in entries:
        c = char(c)
        os_ = [char(o) for o in re.findall(CHAR, others)]
        parts.append(",".join([str(c - prev)] + [str(o - c) for o in os_]))
        prev = c
    doc(out, "Simple case folding: for each character that has others in its case class, those others. Entries are separated by spaces, each the character (as the distance from the previous entry's), then the others (as distances from it), separated by commas.")
    out.append("pub fn case_folding() -> String {")
    out.append(f"  {lit(' '.join(parts))}")
    out.append("}")
    out.append("")
    # property names and values
    names = re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', f("property_names.rs"))
    doc(out, "A property's canonical name, from its name or an alias, normalized (`std.unicode.normalize`).")
    out.append("pub fn property_name(normalized: String) -> Option[String] {")
    out.append("  match normalized {")
    for a, n in names:
        out.append(f"    {lit(a)} => Some({lit(n)}),")
    out.append("    _ => None,")
    out.append("  }")
    out.append("}")
    out.append("")
    src = f("property_values.rs")
    props = re.findall(r'\(\s*"([^"]+)",\s*&\[(.*?)\],\s*\)', src, re.S)
    doc(out, "A property value's canonical name, from its name or an alias, normalized (`std.unicode.normalize`), for the properties that have values here.")
    out.append("pub fn property_value(property: String, normalized: String) -> Option[String] {")
    out.append("  match property {")
    for p, body in props:
        out.append(f"    {lit(p)} => match normalized {{")
        for a, n in re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', body):
            out.append(f"      {lit(a)} => Some({lit(n)}),")
        out.append("      _ => None,")
        out.append("    },")
    out.append("    _ => None,")
    out.append("  }")
    out.append("}")
    print("\n".join(out))


main()
